namespace leaf_detail
{
inline constexpr double kNinf = -std::numeric_limits<double>::infinity();
inline double lae(double a, double b)
{
    if (a == kNinf) return b;
    if (b == kNinf) return a;
    const double m = std::max(a, b);
    return m + std::log1p(std::exp(-std::abs(a - b)));
}
inline double lse(std::span<const double> v)
{
    double m = kNinf;
    for (const double x : v) m = std::max(m, x);
    if (m == kNinf) return kNinf;
    double s = 0.0;
    for (const double x : v) s += std::exp(x - m);
    return m + std::log(s);
}
inline double wrap(double a) { return std::remainder(a, 2.0 * std::numbers::pi); }
}  // namespace leaf_detail

// ─── term 1: one frame's binary log-likelihood ratio δ, contaminated ─────────────────────────────────────────────────────
[[nodiscard]] inline double contaminated_llr(double delta, double eps)
{
    if (std::isnan(delta)) return 0.0;
    delta = std::clamp(delta, -700.0, 700.0);   // |Δ| has saturated at log(1/ε) long before; keeps exp finite
    using leaf_detail::lae;
    const double lp1 = delta >= 0 ? -std::log1p(std::exp(-delta)) : delta - std::log1p(std::exp(delta));   // log σ(δ)
    const double lp0 = lp1 - delta;                                                                          // log σ(−δ)
    const double l1e = std::log1p(-eps), le = std::log(eps);
    return lae(l1e + lp1, le) - lae(l1e + lp0, le);
}

// ─── term 2: one viewpoint's whole contribution, from the sum λ of its frames' contaminated evidence ─────────────────────
[[nodiscard]] inline double viewpoint_llr(double lambda, double eps_v)
{
    using leaf_detail::lae;
    const double l1e = std::log1p(-eps_v), le = std::log(eps_v);
    return lae(l1e + lambda, le) - lae(l1e, le + lambda);
}

// ─── the viewpoint: the sensor's bearing from each jamb, in the door's own frame ─────────────────────────────────────────
struct ViewBearings { double a = 0.0, b = 0.0; };
[[nodiscard]] inline ViewBearings view_bearings(const Aperture& ap, const Eigen::Vector2f& sensor)
{
    const Eigen::Vector2f c = ap.centre_xy(), u = ap.wall_u, n = ap.across_u();
    const Eigen::Vector2f ja = c - 0.5f * ap.w * u, jb = c + 0.5f * ap.w * u;
    const Eigen::Vector2f da = sensor - ja, db = sensor - jb;
    return {std::atan2(double(n.dot(da)), double(u.dot(da))), std::atan2(double(n.dot(db)), double(u.dot(db)))};
}
[[nodiscard]] inline double view_distance(const ViewBearings& p, const ViewBearings& q)
{
    return std::max(std::abs(leaf_detail::wrap(p.a - q.a)), std::abs(leaf_detail::wrap(p.b - q.b)));
}

// The viewpoints this door has been seen from. Each keeps the summed contaminated evidence its frames gave the two static
// binaries; the current one is the one the sensor is within kViewpointRad of (the one it was in, else any earlier one —
// a revisit re-uses its λ — else a new one). `epoch` counts changes of the current viewpoint (the φ filter's epochs).
struct ViewRecord { ViewBearings at; double lam_hinge = 0.0, lam_swing = 0.0; };
struct ViewpointLedger
{
    std::vector<ViewRecord> views;
    int current = -1;
    long epoch = 0;
    // Returns true when the current viewpoint changed (or the first one began).
    bool advance(const ViewBearings& now, double radius)
    {
        if (current >= 0 and view_distance(views[std::size_t(current)].at, now) < radius) return false;
        int pick = -1;
        double best = radius;
        for (std::size_t i = 0; i < views.size(); ++i)
            if (const double d = view_distance(views[i].at, now); d < best) { best = d; pick = int(i); }
        if (pick < 0) { views.push_back({now}); pick = int(views.size()) - 1; }
        current = pick;
        ++epoch;
        return true;
    }
};

// ─── a STATIC binary (hinge jamb, swing side): log-odds = carried prior + Σ_v g(λ_v) ─────────────────────────────────────
// The log-odds the instance publishes is RELATIVE to its believed side, and others write it (the MAP flip negates it, a
// re-created belief re-signs it, a room switch hands a mirror its source's). `sync` reads what the instance holds now: the
// value it last returned (nothing happened), its negation (re-signed: every λ flips with it) or anything else (handed in
// from outside: that becomes the carried prior and the per-viewpoint evidence starts again — it is already inside it).
struct StaticBinaryEvidence
{
    double prior = 0.0;      // the carried log-odds (handed over, or set at creation)
    double sum_g = 0.0;      // Σ_v g(λ_v) over the ledger's views (kept incrementally)
    float  published = 0.0f;
    bool   negated = false;  // the ledger's λ are stored for the side believed when `negated` was false
    [[nodiscard]] double llr() const { return prior + sum_g; }
    void sync(float held, ViewpointLedger& L, double ViewRecord::*lam)
    {
        if (held == published) return;
        if (held == -published) { prior = -prior; sum_g = -sum_g; negated = not negated; published = held; return; }
        prior = held; sum_g = 0.0; published = held;
        for (auto& v : L.views) v.*lam = 0.0;
        negated = false;
    }
    // One frame's binary evidence δ (relative to the believed side) at the ledger's current view.
    float add(double delta, ViewpointLedger& L, double ViewRecord::*lam, double eps, double eps_v)
    {
        if (L.current >= 0 and delta != 0.0 and std::isfinite(delta))
        {
            double& lv = L.views[std::size_t(L.current)].*lam;          // stored for the un-negated side
            const double sgn = negated ? -1.0 : 1.0;
            const double before = viewpoint_llr(lv, eps_v);
            lv += sgn * contaminated_llr(delta, eps);
            sum_g += sgn * (viewpoint_llr(lv, eps_v) - before);
        }
        published = static_cast<float>(llr());
        return published;
    }
};

// ─── the φ filter on the grid: held, or moving, two branches per viewpoint epoch ──────────────────────────────────────────
// The leaf is in one of two regimes: HELD (φ does not change) or MOVING (pushed: φ diffuses at the leaf's swing rate r, a
// step of σ = r·dt per interval). Held → moving at the inferred hazard h (π = 1 − e^{−h·dt}); moving → held at 1/τ_m, τ_m
// = the time to sweep the leaf's whole travel at r (a push carries the leaf across, then it rests). ★Why not a "jump to
// anywhere": a door cannot be at 90° and at 2° 0.3 s apart (try102 t = 411-413 s: 90° → 2° → 103° from one parked
// viewpoint) — the rate limit is what makes such a burst outliers rather than two moves, and it costs nothing when the
// door really moves (it is followed at its own pace).
// ok, wo: normalised log weights over (regime × φ) — [0, N) held, [N, 2N) moving — given "this viewpoint is ok" (frames
// applied) and "aliased" (frames not applied: predicted only); m_ok: log P(this epoch's frames | ok); lam: Σ log l_t(φ')
// — the aliased branch's own explanation, marginalised over φ' (B = log mean exp lam).
struct PhiHmm
{
    bool init = false;
    std::vector<double> ok, wo, lam;
    double m_ok = 0.0;
    [[nodiscard]] std::size_t n() const { return lam.size(); }
    void reset(std::span<const double> log_prior)   // N weights; all HELD
    {
        const std::size_t N = log_prior.size();
        const double z = leaf_detail::lse(log_prior);
        ok.assign(2 * N, leaf_detail::kNinf);
        for (std::size_t k = 0; k < N; ++k) ok[k] = log_prior[k] - z;
        wo = ok;
        lam.assign(N, 0.0);
        m_ok = 0.0;
        init = true;
    }
    [[nodiscard]] double log_aliased_evidence() const
    {
        return lam.empty() ? 0.0 : leaf_detail::lse(lam) - std::log(double(lam.size()));
    }
    // The posterior over φ (normalised log weights over N), the regime marginalised.
    [[nodiscard]] std::vector<double> posterior(double eps_v) const
    {
        const std::size_t N = n();
        std::vector<double> p(N);
        const double a = std::log1p(-eps_v) + m_ok, b = std::log(eps_v) + log_aliased_evidence();
        for (std::size_t k = 0; k < N; ++k)
            p[k] = leaf_detail::lae(a + leaf_detail::lae(ok[k], ok[N + k]), b + leaf_detail::lae(wo[k], wo[N + k]));
        const double z = leaf_detail::lse(p);
        for (double& x : p) x -= z;
        return p;
    }
    [[nodiscard]] double p_moving(double eps_v) const
    {
        const std::size_t N = n();
        const double a = std::log1p(-eps_v) + m_ok, b = std::log(eps_v) + log_aliased_evidence();
        double mv = leaf_detail::kNinf, all = leaf_detail::kNinf;
        for (std::size_t k = 0; k < 2 * N; ++k)
        {
            const double x = leaf_detail::lae(a + ok[k], b + wo[k]);
            all = leaf_detail::lae(all, x);
            if (k >= N) mv = leaf_detail::lae(mv, x);
        }
        return std::exp(mv - all);
    }
    // Collapse at a change of viewpoint: the joint (regime × φ) posterior becomes both branches' prior.
    void new_epoch(double eps_v)
    {
        const std::size_t N = n();
        const double a = std::log1p(-eps_v) + m_ok, b = std::log(eps_v) + log_aliased_evidence();
        std::vector<double> p(2 * N);
        for (std::size_t k = 0; k < 2 * N; ++k) p[k] = leaf_detail::lae(a + ok[k], b + wo[k]);
        const double z = leaf_detail::lse(p);
        for (double& x : p) x -= z;
        ok = p; wo = p;
        lam.assign(N, 0.0);
        m_ok = 0.0;
    }
    // The moving regime's step: a Gaussian of `sigma_steps` grid steps, renormalised at the travel's ends. log K(j|k).
    static std::vector<double> kernel(std::size_t N, double sigma_steps)
    {
        std::vector<double> K(N * N, leaf_detail::kNinf);
        for (std::size_t k = 0; k < N; ++k)
        {
            if (sigma_steps < 1e-3) { K[k * N + k] = 0.0; continue; }
            double z = leaf_detail::kNinf;
            for (std::size_t j = 0; j < N; ++j)
            {
                const double d = (double(j) - double(k)) / sigma_steps;
                K[k * N + j] = -0.5 * d * d;
                z = leaf_detail::lae(z, K[k * N + j]);
            }
            for (std::size_t j = 0; j < N; ++j) K[k * N + j] -= z;
        }
        return K;
    }
    static std::vector<double> convolve(std::span<const double> x, std::span<const double> K, std::size_t N)
    {
        std::vector<double> y(N, leaf_detail::kNinf);
        for (std::size_t k = 0; k < N; ++k)
            if (x[k] != leaf_detail::kNinf)
                for (std::size_t j = 0; j < N; ++j) y[j] = leaf_detail::lae(y[j], x[k] + K[k * N + j]);
        return y;
    }
    // Predict over dt: held stays (1 − π) or starts moving (π); moving moves (σ = r·dt) and stays moving (ρ) or comes to rest.
    // Returns the ok branch's "started moving this step" weights (log, over φ) for the hazard's responsibility.
    std::vector<double> predict(double pi, double rho, double sigma_steps)
    {
        const std::size_t N = n();
        const auto K = kernel(N, sigma_steps);
        const double lpi = pi > 0.0 ? std::log(pi) : leaf_detail::kNinf, l1pi = std::log1p(-std::min(pi, 1.0 - 1e-15));
        const double lrho = rho > 0.0 ? std::log(rho) : leaf_detail::kNinf, l1rho = rho < 1.0 ? std::log1p(-rho) : leaf_detail::kNinf;
        std::vector<double> started;
        for (auto* v : {&ok, &wo})
        {
            const std::span<const double> H(v->data(), N), M(v->data() + N, N);
            const auto DH = convolve(H, K, N), DM = convolve(M, K, N);
            std::vector<double> out(2 * N);
            for (std::size_t j = 0; j < N; ++j)
            {
                out[j]     = leaf_detail::lae(l1pi + H[j], l1rho + DM[j]);
                out[N + j] = leaf_detail::lae(lpi + DH[j], lrho + DM[j]);
            }
            if (v == &ok) { started.resize(N); for (std::size_t j = 0; j < N; ++j) started[j] = lpi + DH[j]; }
            *v = std::move(out);
        }
        return started;
    }
    // Update with one frame's (contaminated, normalised) log-likelihood over φ. `started` from predict (may be empty).
    // Returns P(the leaf started moving this step | ok branch, data) — the hazard's responsibility.
    double update(std::span<const double> logl, const std::vector<double>& started)
    {
        const std::size_t N = n();
        double r = 0.0;
        std::vector<double> t(2 * N);
        for (std::size_t k = 0; k < 2 * N; ++k) t[k] = ok[k] + logl[k % N];
        const double z = leaf_detail::lse(t);
        if (started.size() == N)
        {
            std::vector<double> s(N);
            for (std::size_t j = 0; j < N; ++j) s[j] = started[j] + logl[j];
            r = std::clamp(std::exp(leaf_detail::lse(s) - z), 0.0, 1.0);
        }
        for (std::size_t k = 0; k < 2 * N; ++k) ok[k] = t[k] - z;
        m_ok += z;
        for (std::size_t k = 0; k < N; ++k) lam[k] += logl[k];
        return r;
    }
    [[nodiscard]] double p_ok(double eps_v) const
    {
        const double a = std::log1p(-eps_v) + m_ok, b = std::log(eps_v) + log_aliased_evidence();
        return std::exp(a - leaf_detail::lae(a, b));
    }
};

// ─── the whole leaf channel's state, carried on the door instance ───────────────────────────────────────────────────────
// The leaf is (hinge jamb, swing side, regime, φ). Hinge and swing are static; φ is filtered PER (hinge, swing) hypothesis —
// a leaf at 114° behind the wall under one swing is not a leaf at 114° under the other (test_door_phi_stability (h): one
// φ filter shared by the four hypotheses held 114° after the swing flipped to the true side, where the leaf stood at 90°).
// Filters are indexed absolutely: (Near, +1), (Near, −1), (Far, +1), (Far, −1).
[[nodiscard]] inline int leaf_index(HingeSide h, float swing) { return (h == HingeSide::Near ? 0 : 2) + (swing > 0.0f ? 0 : 1); }
struct LeafChannel
{
    ViewpointLedger views;
    StaticBinaryEvidence hinge, swing;
    std::array<PhiHmm, 4> phi;
    double move_a = kLeafMoveHyperShape, move_b = kLeafMoveHyperTimeS;   // the move hazard's Gamma posterior
    float out_mean = std::numeric_limits<float>::quiet_NaN(), out_sigma = std::numeric_limits<float>::quiet_NaN();
    [[nodiscard]] double hazard() const { return move_a / move_b; }
};

struct LeafChannelInput
{
    // The frame's (φ, log-likelihood) curves on the grid, as FieldResult names them (empty = not scored this frame).
    std::vector<std::pair<float, float>> bb, ob, bs, os;
    // The passage anchor's swing evidence this frame, relative to the believed swing (0 = none).
    double anchor_swing_delta = 0.0;
    bool have_sensor = false;
    Eigen::Vector2f sensor = Eigen::Vector2f::Zero();   // the LiDAR origin, in the frame the aperture is in
    float dt = std::numeric_limits<float>::infinity();  // since the last step; +inf = the first look
    bool  cmd_active = false;                           // our own open/close is running: the prior is its trajectory
    float cmd_mean = 0.0f, cmd_sigma = 0.0f;
    float phi_min = 0.0f, phi_max = 2.0944f;
    int   nstep = 25;
    float view_rad = 0.0873f;                            // kViewpointRad: the φ grid's step
    float swing_rate = 2.0f;                             // r (rad/s): how fast a pushed leaf can swing (the provider's rate)
    double eps = kLeafFrameOutlierRate, eps_v = kLeafViewOutlierRate;
    double eps_v_phi = kLeafViewOutlierRate;
};

struct LeafChannelResult
{
    PhiPosteriorStep post;
    bool new_view = false, hinge_flipped = false, swing_flipped = false;
    double pi_move = 0.0;       // the predict step's move probability (diagnostic)
    double frame_hinge = 0.0, frame_swing = 0.0;   // this frame's raw binary evidence δ (diagnostic)
    double p_ok = 1.0;          // P(this viewpoint is not aliased) (diagnostic)
    double p_moving = 0.0;      // P(the leaf is being pushed now) (diagnostic)
    float prior_mean = 0.0f, prior_sigma = 0.0f;   // the PREDICTED belief's moments (the trace's prior columns)
    std::vector<std::pair<float, float>> frame_loglik;   // the frame's (hinge × swing)-marginal curve (empty = none)
};

[[nodiscard]] inline std::vector<double> gaussian_log_prior(float lo, float hi, int n, float mean, float sigma)
{
    std::vector<double> p(std::size_t(std::max(n, 2)));
    const double sp = std::max(1e-4, double(sigma));
    for (int k = 0; k < n; ++k)
    {
        const double phi = lo + (hi - lo) * double(k) / double(n - 1);
        const double d = (phi - mean) / sp;
        p[std::size_t(k)] = -0.5 * d * d;
    }
    return p;
}

// One frame. `hinge_llr` / `swing_llr` / `phi_est` / `phi_sigma` are the instance's (read for what others wrote, then
// written); `b` is the belief whose leaf hangs from the MAP hinge and swings to the MAP side.
inline LeafChannelResult leaf_channel_step(LeafChannel& ch, rc::DoorBelief& b, float& hinge_llr, float& swing_llr,
                                           float& phi_est, float& phi_sigma, const LeafChannelInput& in)
{
    using leaf_detail::lae;
    using leaf_detail::lse;
    using leaf_detail::kNinf;
    LeafChannelResult res;
    const int N = std::max(2, in.nstep);
    const std::size_t NN = std::size_t(N);
    const auto log_sig = [](double l) { return l >= 0 ? -std::log1p(std::exp(-l)) : l - std::log1p(std::exp(l)); };

    // ── what others wrote since the last step ───────────────────────────────────────────────────────────────────────
    ch.hinge.sync(hinge_llr, ch.views, &ViewRecord::lam_hinge);
    ch.swing.sync(swing_llr, ch.views, &ViewRecord::lam_swing);
    const bool first_look = not std::isfinite(in.dt);
    if (not ch.phi[0].init or ch.phi[0].n() != NN or phi_est != ch.out_mean or phi_sigma != ch.out_sigma)
    {
        // A (φ, σ) handed in (a new door, a room switch's mirror) is the angle of the leaf AS BELIEVED: its filter takes
        // it. The other hypotheses take only what does not depend on the hypothesis — P(shut) (φ = 0 is the wall plane
        // whatever the hinge and swing) — and nothing about the open angle: uniform over it.
        const bool none = first_look or not std::isfinite(phi_est) or not std::isfinite(phi_sigma);
        const auto prior = none ? std::vector<double>(NN, 0.0)
                                : gaussian_log_prior(in.phi_min, in.phi_max, N, phi_est, std::max(phi_sigma, 1e-3f));
        std::vector<double> other(NN, 0.0);
        if (not none)
        {
            const double z = lse(prior), p0 = std::clamp(std::exp(prior[0] - z), 1e-12, 1.0 - 1e-12);
            other[0] = std::log(p0);
            for (std::size_t k = 1; k < NN; ++k) other[k] = std::log((1.0 - p0) / double(N - 1));
        }
        const int believed = leaf_index(b.params().leaf.hinge, b.params().leaf.swing);
        for (int j = 0; j < 4; ++j) ch.phi[std::size_t(j)].reset(j == believed ? prior : other);
    }

    // ── the viewpoint ───────────────────────────────────────────────────────────────────────────────────────────────
    if (in.have_sensor)
        res.new_view = ch.views.advance(view_bearings(b.aperture(), in.sensor), in.view_rad);
    else if (ch.views.current < 0)
        ch.views.advance({0.0, 0.0}, in.view_rad);   // no sensor known: one viewpoint (the bound still holds)
    // The φ filters' epoch: frames that share ONE error — a change of viewpoint starts a new one. ★Not the passage of time
    // (tried: renewing every kRegistrationTauS let a fresh epoch's "aliased" branch absorb a door that really shut — the
    // channel took 51 frames to follow it from a new viewpoint, and never from a parked one).
    if (res.new_view) for (auto& f : ch.phi) f.new_epoch(in.eps_v_phi);

    // ── predict φ ───────────────────────────────────────────────────────────────────────────────────────────────────
    double pi = 0.0;
    std::array<std::vector<double>, 4> started;
    if (in.cmd_active)
    {
        const auto prior = gaussian_log_prior(in.phi_min, in.phi_max, N, in.cmd_mean, in.cmd_sigma);   // a known intervention
        for (auto& f : ch.phi) f.reset(prior);
    }
    else if (not first_look and in.dt > 0.0f)
    {
        const double step = double(in.phi_max - in.phi_min) / double(N - 1);
        const double rate = std::max(1e-3, double(in.swing_rate));
        const double tau_m = double(in.phi_max - in.phi_min) / rate;   // τ_m: a push sweeps the leaf's travel, then it rests
        pi = -std::expm1(-ch.hazard() * double(in.dt));
        for (int j = 0; j < 4; ++j)
            started[std::size_t(j)] = ch.phi[std::size_t(j)].predict(pi, std::exp(-double(in.dt) / tau_m), rate * double(in.dt) / step);
    }
    res.pi_move = pi;
    {
        // The PREDICTED belief's moments (the trace's prior columns): the four filters mixed by the carried P(hinge)·P(swing).
        const HingeSide ph = b.params().leaf.hinge, poh = ph == HingeSide::Near ? HingeSide::Far : HingeSide::Near;
        const float psw = b.params().leaf.swing;
        std::vector<double> mix(NN, kNinf);
        for (int h = 0; h < 2; ++h)
            for (int sw = 0; sw < 2; ++sw)
            {
                const double lw = log_sig(h == 0 ? double(hinge_llr) : -double(hinge_llr)) + log_sig(sw == 0 ? double(swing_llr) : -double(swing_llr));
                const auto pj = ch.phi[std::size_t(leaf_index(h == 0 ? ph : poh, sw == 0 ? psw : -psw))].posterior(in.eps_v_phi);
                for (std::size_t k = 0; k < NN; ++k) mix[k] = lae(mix[k], lw + pj[k]);
            }
        const double z = lse(mix);
        double m = 0.0, m2 = 0.0;
        for (std::size_t k = 0; k < NN; ++k)
        {
            const double phi = in.phi_min + (in.phi_max - in.phi_min) * double(k) / double(N - 1), w = std::exp(mix[k] - z);
            m += w * phi; m2 += w * phi * phi;
        }
        res.prior_mean = float(m);
        res.prior_sigma = float(std::sqrt(std::max(0.0, m2 - m * m)));
    }

    // ── the four leaf hypotheses: this frame's evidence for each, under each one's own predicted φ ─────────────────────
    const HingeSide bh = b.params().leaf.hinge, oh = bh == HingeSide::Near ? HingeSide::Far : HingeSide::Near;
    const float bsw = b.params().leaf.swing;
    // [hinge: 0 believed, 1 other][swing: 0 believed, 1 other] → the input curve and the absolute filter.
    const std::vector<std::pair<float, float>>* curve[2][2] = {{&in.bb, &in.bs}, {&in.ob, &in.os}};
    int fidx[2][2];
    bool have[2][2];
    double e[2][2];
    for (int h = 0; h < 2; ++h)
        for (int sw = 0; sw < 2; ++sw)
        {
            fidx[h][sw] = leaf_index(h == 0 ? bh : oh, sw == 0 ? bsw : -bsw);
            have[h][sw] = curve[h][sw]->size() == NN;
            e[h][sw] = kNinf;
            if (have[h][sw])
            {
                const auto pred = ch.phi[std::size_t(fidx[h][sw])].posterior(in.eps_v_phi);
                for (std::size_t k = 0; k < NN; ++k)
                {
                    const double l = double((*curve[h][sw])[k].second);
                    if (std::isfinite(l)) e[h][sw] = lae(e[h][sw], l + pred[k]);
                }
            }
        }
    const double hl0 = hinge_llr, sl0 = swing_llr;
    const double lp_h[2] = {log_sig(hl0), log_sig(-hl0)}, lp_s[2] = {log_sig(sl0), log_sig(-sl0)};
    if (have[0][0])
    {
        double num = kNinf, den = kNinf;
        for (int sw = 0; sw < 2; ++sw) if (have[0][sw] and have[1][sw]) { num = lae(num, lp_s[sw] + e[0][sw]); den = lae(den, lp_s[sw] + e[1][sw]); }
        if (std::isfinite(num) and std::isfinite(den)) res.frame_hinge = num - den;
        num = kNinf; den = kNinf;
        for (int h = 0; h < 2; ++h) if (have[h][0] and have[h][1]) { num = lae(num, lp_h[h] + e[h][0]); den = lae(den, lp_h[h] + e[h][1]); }
        if (std::isfinite(num) and std::isfinite(den)) res.frame_swing = num - den;
        // The frame's φ curve under the leaf mixture, for the trace: log Σ P(h)P(s) L_hs(φ) over the hypotheses scored.
        res.frame_loglik.reserve(NN);
        for (std::size_t k = 0; k < NN; ++k)
        {
            double mix = kNinf;
            for (int h = 0; h < 2; ++h)
                for (int sw = 0; sw < 2; ++sw)
                    if (have[h][sw]) { const double l = double((*curve[h][sw])[k].second); if (std::isfinite(l)) mix = lae(mix, lp_h[h] + lp_s[sw] + l); }
            res.frame_loglik.emplace_back(in.bb[k].first, std::isfinite(mix) ? float(mix) : -std::numeric_limits<float>::infinity());
        }
    }
    res.frame_swing += in.anchor_swing_delta;

    // ── each scored hypothesis's φ filter takes the frame, contaminated ─────────────────────────────────────────────
    double r_move = 0.0, w_move = 0.0;
    for (int h = 0; h < 2; ++h)
        for (int sw = 0; sw < 2; ++sw)
        {
            if (not have[h][sw]) continue;
            const auto& c = *curve[h][sw];
            std::vector<double> frame(NN);
            for (std::size_t k = 0; k < NN; ++k) frame[k] = double(c[k].second);
            const double z = lse(frame);
            if (not std::isfinite(z)) continue;
            const double l1e = std::log1p(-in.eps), leN = std::log(in.eps / double(N));
            std::vector<double> logl(NN);
            for (std::size_t k = 0; k < NN; ++k)
                logl[k] = lae(l1e + (std::isfinite(frame[k]) ? frame[k] - z : kNinf), leN);
            if (h == 0 and sw == 0)
            {
                // The measured flag, unchanged: the believed leaf's likelihood's coefficient of variation across the grid
                // (see phi_posterior_step) — it reports whether this frame discriminated, it gates nothing.
                double sum = 0.0, v = 0.0;
                std::vector<double> lin(NN);
                for (std::size_t k = 0; k < NN; ++k) { lin[k] = std::isfinite(frame[k]) ? std::exp(frame[k] - z) : 0.0; sum += lin[k]; }
                const double mu = sum / double(N);
                for (const double x : lin) v += (x - mu) * (x - mu);
                res.post.cv = mu > 0.0 ? float(std::sqrt(v / double(N)) / mu) : 0.0f;
                res.post.measured = res.post.cv > 0.10f;
            }
            auto& f = ch.phi[std::size_t(fidx[h][sw])];
            const double wj = std::exp(lp_h[h] + lp_s[sw]);
            r_move += wj * f.update(logl, started[std::size_t(fidx[h][sw])]);
            w_move += wj;
        }

    // ── the static binaries: contaminated, pooled per viewpoint; the geometry hangs from the MAP leaf ───────────────────
    hinge_llr = ch.hinge.add(res.frame_hinge, ch.views, &ViewRecord::lam_hinge, in.eps, in.eps_v);
    swing_llr = ch.swing.add(res.frame_swing, ch.views, &ViewRecord::lam_swing, in.eps, in.eps_v);
    res.hinge_flipped = adopt_map_hinge(b, hinge_llr);
    res.swing_flipped = adopt_map_swing(b, swing_llr);
    ch.hinge.sync(hinge_llr, ch.views, &ViewRecord::lam_hinge);
    ch.swing.sync(swing_llr, ch.views, &ViewRecord::lam_swing);

    // ── the posterior over φ: the four filters mixed by P(hinge)·P(swing) ──────────────────────────────────────────────
    const HingeSide nh = b.params().leaf.hinge, noh = nh == HingeSide::Near ? HingeSide::Far : HingeSide::Near;
    const float nsw = b.params().leaf.swing;
    const double hl = hinge_llr, sl = swing_llr;
    std::vector<double> lp(NN, kNinf);
    double p_ok = 0.0, p_mv = 0.0;
    for (int h = 0; h < 2; ++h)
        for (int sw = 0; sw < 2; ++sw)
        {
            const double lw = log_sig(h == 0 ? hl : -hl) + log_sig(sw == 0 ? sl : -sl);
            const auto& f = ch.phi[std::size_t(leaf_index(h == 0 ? nh : noh, sw == 0 ? nsw : -nsw))];
            const auto pj = f.posterior(in.eps_v_phi);
            for (std::size_t k = 0; k < NN; ++k) lp[k] = lae(lp[k], lw + pj[k]);
            p_ok += std::exp(lw) * f.p_ok(in.eps_v_phi);
            p_mv += std::exp(lw) * f.p_moving(in.eps_v_phi);
        }
    res.p_ok = p_ok;
    res.p_moving = p_mv;
    if (not first_look and not in.cmd_active and std::isfinite(in.dt) and in.dt > 0.0f)
    {
        // Expected moves started this step (the scored filters' responsibility; unscored: the prior's π) over time at rest.
        ch.move_a += w_move > 0.0 ? r_move / w_move : pi;
        ch.move_b += double(in.dt) * (1.0 - res.p_moving);
    }
    // ── collapsed to what the rest of the agent reads ───────────────────────────────────────────────────────────────
    PhiPosteriorStep& out = res.post;
    const double z = lse(lp);
    for (double& x : lp) x -= z;
    double num = 0.0, den = 0.0, best = -1.0;
    out.curve.reserve(NN);
    out.log_curve.reserve(NN);
    const double lpmax = *std::ranges::max_element(lp);
    for (std::size_t k = 0; k < NN; ++k)
    {
        const float phi = in.phi_min + (in.phi_max - in.phi_min) * float(k) / float(N - 1);
        const double w = std::exp(lp[k]);
        out.log_curve.emplace_back(phi, lp[k] - lpmax);
        out.curve.emplace_back(phi, float(std::exp(lp[k] - lpmax)));
        num += w * phi; den += w;
        if (w > best) best = w;
    }
    out.w_lik_best = float(best);
    out.mean = float(num / den);
    double var = 0.0;
    for (std::size_t k = 0; k < NN; ++k)
    {
        const float phi = out.log_curve[k].first;
        var += std::exp(lp[k]) * (phi - out.mean) * (phi - out.mean);
    }
    out.sigma = float(std::sqrt(std::max(0.0, var / den)));
    phi_est = out.mean;
    phi_sigma = out.sigma;
    ch.out_mean = phi_est;
    ch.out_sigma = phi_sigma;
    return res;
}

