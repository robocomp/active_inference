#!/usr/bin/env python3
"""make_countable.py — one-off: bed_concept -> countable_concept (kept for the record).

Plan 2026-11-14 countable-concept step 1, Task 2. Copies bed_concept's TRACKED sources
(CMakeLists.txt, Makefile, generated/, src/, tests/, bed_concept.cdsl — never etc/, meshes/, bin/, build/)
to countable_concept/, renames files bed_* -> countable_*, renames identifiers (Bed* -> Countable*,
bed_* / *_bed -> countable_*, BED -> COUNTABLE), renames the config sections [BedModel] -> [Model],
[BedConcept] -> [Concept] (and drops the class word from [Concept]/[Model] keys that carried it), and
writes the old->new key map to countable_concept/KEYMAP.md for Task 4.

The class STRING literals ("bed", "bed_", the mesh path, ...) are NOT handled here: they become
cfg_.concept_class / cfg_.agent_name by hand afterwards (Task 2 Step 2), as are reading Concept.Class /
Agent.name in countable_config.cpp, and dropping the perception-card test (tests/countable_card_test.cpp
and its CMake entry) until Task 4 brings a parameterised one.

Run from the repo root. Refuses to overwrite an existing countable_concept/.
"""
import pathlib
import re
import subprocess
import sys

SRC = pathlib.Path("bed_concept")
DST = pathlib.Path("countable_concept")
KEEP_TOP = {"CMakeLists.txt", "Makefile", "bed_concept.cdsl"}
KEEP_DIRS = {"generated", "src", "tests"}

# Config sections. Order matters: the "class word in the key" forms first.
SECTION_RULES = [
    (re.compile(r"\bBedConcept\.Bed([A-Z]\w*)"), r"Concept.\1"),
    (re.compile(r"\bBedConcept\.([A-Z]\w*)"), r"Concept.\1"),
    (re.compile(r"\bBedModel\.Bed([A-Z]\w*)"), r"Model.\1"),
    (re.compile(r"\bBedModel\.([A-Z]\w*)"), r"Model.\1"),
    (re.compile(r"\[BedConcept\]"), "[Concept]"),
    (re.compile(r"\[BedModel\]"), "[Model]"),
]
# Identifiers. "bed" only where it is part of an identifier (adjacent '_'), so prose words in comments
# ("a bed is ...", "embedded", "beds") are left alone.
IDENT_RULES = [
    (re.compile(r"Bed(?![a-z])"), "Countable"),
    (re.compile(r"(?<![A-Z])BED(?![A-Z])"), "COUNTABLE"),
    (re.compile(r"(?<![A-Za-z0-9])bed(?=_)"), "countable"),
    (re.compile(r"(?<=_)bed(?![a-z])"), "countable"),
]
# Every config read: reader lambdas getf/geti/getb/gets and the Reader methods.
READ_CALL = re.compile(r"\b(?:get[fibsd]|\.req|\.opt|\.opt_cast|\.maybe|\.f|\.i|\.b|\.s|\.d|\.v)\s*(?:<[^>()]*>)?\(\s*\"([A-Za-z]\w*\.[A-Za-z]\w*)\"")


def rename_text(t: str) -> str:
    for rx, rep in SECTION_RULES + IDENT_RULES:
        t = rx.sub(rep, t)
    return t


def new_key(k: str) -> str:
    for rx, rep in SECTION_RULES:
        k = rx.sub(rep, k)
    return k


def main() -> int:
    if DST.exists():
        print(f"{DST} exists — refusing")
        return 1
    files = subprocess.run(["git", "ls-files", str(SRC)], check=True, capture_output=True, text=True).stdout.split()
    keymap = {}
    for f in map(pathlib.Path, files):
        rel = f.relative_to(SRC)
        if not (len(rel.parts) == 1 and rel.name in KEEP_TOP) and rel.parts[0] not in KEEP_DIRS:
            continue
        if "build" in rel.parts:
            continue
        out = DST / pathlib.Path(*[re.sub(r"^bed_", "countable_", p) for p in rel.parts])
        out.parent.mkdir(parents=True, exist_ok=True)
        text = f.read_text(encoding="utf-8")
        if f.suffix in {".cpp", ".h"}:
            for k in READ_CALL.findall(text):
                if new_key(k) != k:
                    keymap[k] = new_key(k)
        out.write_text(rename_text(text), encoding="utf-8")
    # The top-level CMakeLists installs etc/config.toml, which countable_concept does not have
    # (each class folder keeps its own etc/).
    top = DST / "CMakeLists.txt"
    top.write_text("".join(l for l in top.read_text().splitlines(keepends=True)
                           if not l.startswith("INSTALL(FILES etc/config.toml")))
    with open(DST / "KEYMAP.md", "w", encoding="utf-8") as km:
        km.write("# countable_concept config key map (old bed_concept key -> new key), generated by tools/make_countable.py\n")
        for old in sorted(keymap):
            km.write(f"{old} -> {keymap[old]}\n")
    print(f"{DST} written; {len(keymap)} renamed keys in {DST}/KEYMAP.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
